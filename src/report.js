'use strict';
const path = require('path');

const ICON = { critical: '✖', high: '▲', medium: '●', low: '○', info: 'i' };
const COLOR = { critical: 31, high: 33, medium: 35, low: 36, info: 90 };

function terminal(r, useColor) {
  const c = (code, s) => (useColor ? '\x1b[' + code + 'm' + s + '\x1b[0m' : s);
  const lines = [];
  lines.push('');
  lines.push(c(1, 'safe-to-ship') + '  ' + path.basename(r.root) + '  (' + r.filesScanned + ' files)');
  lines.push('');
  if (!r.findings.length) lines.push(c(32, '  No problems found by these checks.'));
  for (const f of r.findings) {
    const where = f.file ? '  ' + c(90, f.file + (f.line ? ':' + f.line : '')) : '';
    lines.push('  ' + c(COLOR[f.severity], ICON[f.severity] + ' ' + f.severity.toUpperCase().padEnd(8)) + ' ' + f.title + where);
    const fx = f.fix.split('\n')[0];
    lines.push('      ' + c(90, 'Fix: ' + (fx.length > 110 ? fx.slice(0, 107).replace(/\s+\S*$/, '') + ' …' : fx)));
  }
  lines.push('');
  const v = r.counts.critical ? 31 : r.counts.high ? 33 : 32;
  lines.push('  ' + c(1, 'Score ' + r.score + '/100') + '  ' + c(v, r.verdict) + '   ' +
    ['critical', 'high', 'medium', 'low'].map((s) => r.counts[s] + ' ' + s).join(' · '));
  lines.push('  ' + c(90, 'Full report with every fix: npx github:Shivamkole1969/safe-to-ship --report'));
  lines.push('');
  return lines.join('\n');
}

function markdown(r) {
  const out = [];
  out.push('# safe-to-ship report: ' + path.basename(r.root));
  out.push('');
  out.push('**' + r.verdict + '** · score **' + r.score + '/100** · ' + ['critical', 'high', 'medium', 'low', 'info'].map((s) => r.counts[s] + ' ' + s).join(' · ') + ' · ' + r.filesScanned + ' files scanned');
  out.push('');
  out.push('Checked: hard-coded keys, .env files, Supabase Row Level Security and Firebase rules, paid AI routes without login or rate limits, launch basics (title, description, share image, robots, sitemap, security headers, privacy policy) and app-store blockers. These are automated checks of the code in this folder. They do not replace a penetration test, and a clean report does not prove the app is secure.');
  out.push('');
  let area = null;
  for (const f of r.findings) {
    if (f.area !== area) { area = f.area; out.push('## ' + area); out.push(''); }
    out.push('### ' + f.severity.toUpperCase() + ': ' + f.title);
    if (f.file) out.push('`' + f.file + (f.line ? ':' + f.line : '') + '`');
    out.push('');
    out.push(f.detail);
    out.push('');
    out.push('**Fix:** ' + f.fix);
    out.push('');
  }
  if (!r.findings.length) out.push('No problems found by these checks.');
  out.push('---');
  out.push('Generated by [safe-to-ship](https://github.com/Shivamkole1969/safe-to-ship), free and open source (MIT).');
  return out.join('\n') + '\n';
}

module.exports = { terminal, markdown };
